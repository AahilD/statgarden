"""Write transform/models/staging/_sources.yml from the raw tables in DuckDB.

dbt needs every raw table declared as a source. Generating the list means a new
endpoint in endpoints.yaml never needs a hand edit here.

    uv run python -m ingest.gen_sources
"""

from __future__ import annotations

import duckdb
import yaml

from ingest.paths import DB_PATH, ROOT
from ingest.registry import load_registry

OUT = ROOT / "transform" / "models" / "staging" / "_sources.yml"


def main() -> None:
    _, eps = load_registry()
    by_name = {e.name: e for e in eps}
    con = duckdb.connect(str(DB_PATH), read_only=True)
    tables = [
        t
        for (t,) in con.execute(
            "SELECT table_name FROM information_schema.tables WHERE table_name LIKE 'raw\\_%' ESCAPE '\\' ORDER BY 1"
        ).fetchall()
    ]
    con.close()

    entries = []
    for t in tables:
        ep = None if t.startswith("raw__") else by_name.get(t[len("raw_") :].split("__")[0])
        if t.startswith("raw__"):
            desc = "Loader bookkeeping."
        elif ep is None:
            desc = "Unknown endpoint."
        else:
            desc = f"{ep.source} {ep.endpoint}" + (f": {ep.note}" if ep.note else "")
        entries.append({"name": t, "description": desc})

    doc = {"version": 2, "sources": [{"name": "raw", "schema": "main", "tables": entries}]}
    header = "# GENERATED by `uv run python -m ingest.gen_sources` (make sources). Don't edit by hand.\n"
    OUT.write_text(header + yaml.safe_dump(doc, sort_keys=False, width=120))
    print(f"wrote {len(entries)} sources to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
